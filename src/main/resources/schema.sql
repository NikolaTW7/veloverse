-- VeloVerse database schema (see Docs/database-design.md).
-- Tables are added here as each feature is built. Every statement is safe to re-run.

CREATE TABLE IF NOT EXISTS bicycle_types (
    type_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    description   TEXT NOT NULL,
    best_use      TEXT,
    advantages    TEXT,
    disadvantages TEXT
);

CREATE TABLE IF NOT EXISTS materials (
    material_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    description   TEXT NOT NULL,
    advantages    TEXT,
    disadvantages TEXT
);

CREATE TABLE IF NOT EXISTS component_systems (
    system_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS components (
    component_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id    INTEGER NOT NULL REFERENCES component_systems (system_id),
    name         VARCHAR(100) NOT NULL UNIQUE,
    description  TEXT NOT NULL,
    purpose      TEXT,
    operation    TEXT,
    image_url    VARCHAR(255)
);

-- Many-to-many link: a component can use several materials and a material can be used by many components
CREATE TABLE IF NOT EXISTS component_materials (
    component_id INTEGER NOT NULL REFERENCES components (component_id),
    material_id  INTEGER NOT NULL REFERENCES materials (material_id),
    PRIMARY KEY (component_id, material_id)
);

CREATE TABLE IF NOT EXISTS brands (
    brand_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    country     VARCHAR(100),
    description TEXT
);

-- Bicycle models. Each bicycle belongs to one brand, one bicycle type and one frame material.
CREATE TABLE IF NOT EXISTS bicycles (
    bicycle_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id          INTEGER NOT NULL REFERENCES brands (brand_id),
    type_id           INTEGER NOT NULL REFERENCES bicycle_types (type_id),
    frame_material_id INTEGER REFERENCES materials (material_id), -- NULL = not confirmed
    name              VARCHAR(100) NOT NULL,
    year              INTEGER,
    weight_kg         NUMERIC(5,2),
    wheel_size        VARCHAR(30),
    brake_system      VARCHAR(100),
    drivetrain        VARCHAR(150),
    gears             INTEGER,
    description       TEXT,
    image_url         VARCHAR(255),
    UNIQUE (brand_id, name, year)
);

