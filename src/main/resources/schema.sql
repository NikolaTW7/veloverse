-- VeloVerse database schema.
-- Tables are added here as each feature is built. Every statement is safe to re-run.
-- Spring Boot runs this file on every start-up (spring.sql.init.mode=always in application.properties),
-- and then runs data.sql to fill the tables with starter content.
--
-- Words used in the tables below:
--   CREATE TABLE IF NOT EXISTS   creates the table only when it is missing, so an existing table
--                                and its rows are left alone when the application starts again.
--   PRIMARY KEY                  the column that identifies each row. It must be unique and not NULL.
--   GENERATED BY DEFAULT AS IDENTITY
--                                PostgreSQL fills in the next number (1, 2, 3 ...) automatically when
--                                an INSERT does not give one. BY DEFAULT still allows an explicit ID,
--                                which the undo steps in the db folder use to restore old rows.
--   NOT NULL                     the column must always have a value.
--   UNIQUE                       no two rows may have the same value. data.sql relies on this for
--                                ON CONFLICT DO NOTHING.
--   REFERENCES other (column)    a foreign key. The value must match an existing row in the other
--                                table, so a row can never point to something that does not exist.
--   VARCHAR(n) and TEXT          VARCHAR has a maximum length of n characters, TEXT has no fixed limit.

-- The general kinds of bicycle (Road Bike, Mountain Bike ...).
-- name is UNIQUE so the same type cannot be added twice.
-- advantages and disadvantages hold one point per line.
CREATE TABLE IF NOT EXISTS bicycle_types (
    type_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    description   TEXT NOT NULL,
    best_use      TEXT,
    advantages    TEXT,
    disadvantages TEXT
);

-- Materials that frames and parts are made of (Aluminium, Carbon Fibre, Steel ...).
CREATE TABLE IF NOT EXISTS materials (
    material_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    description   TEXT NOT NULL,
    advantages    TEXT,
    disadvantages TEXT
);

-- Groups of related parts (Frame System, Drivetrain, Braking System ...).
CREATE TABLE IF NOT EXISTS component_systems (
    system_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description TEXT NOT NULL
);

-- Individual bicycle parts (Frame, Chain, Brake Lever ...).
-- One-to-many: each component belongs to exactly one component system (system_id is NOT NULL),
-- and one system can have many components.
CREATE TABLE IF NOT EXISTS components (
    component_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id    INTEGER NOT NULL REFERENCES component_systems (system_id),
    name         VARCHAR(100) NOT NULL UNIQUE,
    description  TEXT NOT NULL,
    purpose      TEXT,
    operation    TEXT,
    image_url    VARCHAR(255)
);

-- Many-to-many link: a component can use several materials and a material can be used by many components
-- This is a join table: each row is just one (component, material) pair of foreign keys.
-- The PRIMARY KEY is made of both columns together, so the same pair can only be stored once.
CREATE TABLE IF NOT EXISTS component_materials (
    component_id INTEGER NOT NULL REFERENCES components (component_id),
    material_id  INTEGER NOT NULL REFERENCES materials (material_id),
    PRIMARY KEY (component_id, material_id)
);

-- Bicycle manufacturers. country and description are optional (they may be NULL).
CREATE TABLE IF NOT EXISTS brands (
    brand_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    country     VARCHAR(100),
    description TEXT
);

-- Bicycle models. Each bicycle belongs to one brand and one bicycle type, and has at most one frame material.
-- These are one-to-many relationships: one brand (or type, or material) can have many bicycles.
-- weight_kg is NUMERIC(5,2): up to 5 digits in total, 2 of them after the decimal point.
-- UNIQUE (brand_id, name, year) means one brand cannot have two models with the same name and year.
CREATE TABLE IF NOT EXISTS bicycles (
    bicycle_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id          INTEGER NOT NULL REFERENCES brands (brand_id),
    type_id           INTEGER NOT NULL REFERENCES bicycle_types (type_id),
    frame_material_id INTEGER REFERENCES materials (material_id), -- NULL = not confirmed
    name              VARCHAR(100) NOT NULL,
    year              INTEGER,
    weight_kg         NUMERIC(5,2),
    wheel_size        VARCHAR(30),
    brake_system      VARCHAR(100),
    drivetrain        VARCHAR(150),
    gears             INTEGER,
    description       TEXT,
    image_url         VARCHAR(255),
    UNIQUE (brand_id, name, year)
);

-- Extra details for brands and bicycle models (added October 2026).
-- The columns are optional, so rows without them stay valid, and IF NOT EXISTS keeps this safe to re-run.
-- ADD COLUMN IF NOT EXISTS adds the column to a database that was created before these
-- columns existed, and does nothing when the column is already there.
ALTER TABLE brands ADD COLUMN IF NOT EXISTS website VARCHAR(255);
ALTER TABLE brands ADD COLUMN IF NOT EXISTS specialities TEXT;

-- features, advantages and disadvantages hold one item per line.
-- source_url is the web page that the facts about the model were taken from.
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS intended_use TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS features TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS advantages TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS disadvantages TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS source_url VARCHAR(255);

-- The frame material is optional: it stays NULL when the exact material of a model
-- cannot be confirmed. Dropping NOT NULL is safe to repeat on every start-up.
-- It is needed because CREATE TABLE IF NOT EXISTS above never changes a table that already
-- exists, so a database created when this column was still NOT NULL would keep that rule.
ALTER TABLE bicycles ALTER COLUMN frame_material_id DROP NOT NULL;
