ALTER TABLE brands ADD COLUMN IF NOT EXISTS specialities TEXT;

ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS intended_use TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS features TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS advantages TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS disadvantages TEXT;
ALTER TABLE bicycles ADD COLUMN IF NOT EXISTS source_url VARCHAR(255);

-- The frame material is optional: it stays NULL when the exact material of a model
-- cannot be confirmed. Dropping NOT NULL is safe to repeat on every start-up.
ALTER TABLE bicycles ALTER COLUMN frame_material_id DROP NOT NULL;
